// 컷신에 박히는 큰 글자(PHASE 2, #1 …). 캔버스 폰트를 쓰면 픽셀이 뭉개져서
// 5×7 도트 글리프를 직접 찍는다. 한글은 여기서 안 그린다 — DOM 대사창이 맡는다.

const GLYPHS = {
  P: ['11110', '10001', '10001', '11110', '10000', '10000', '10000'],
  H: ['10001', '10001', '10001', '11111', '10001', '10001', '10001'],
  A: ['01110', '10001', '10001', '11111', '10001', '10001', '10001'],
  S: ['01111', '10000', '10000', '01110', '00001', '00001', '11110'],
  E: ['11111', '10000', '10000', '11110', '10000', '10000', '11111'],
  '#': ['01010', '01010', '11111', '01010', '11111', '01010', '01010'],
  0: ['01110', '10001', '10011', '10101', '11001', '10001', '01110'],
  1: ['00100', '01100', '00100', '00100', '00100', '00100', '01110'],
  2: ['01110', '10001', '00001', '00010', '00100', '01000', '11111'],
  3: ['11111', '00010', '00100', '00010', '00001', '10001', '01110'],
  4: ['00010', '00110', '01010', '10010', '11111', '00010', '00010'],
  5: ['11111', '10000', '11110', '00001', '00001', '10001', '01110'],
  6: ['00110', '01000', '10000', '11110', '10001', '10001', '01110'],
  7: ['11111', '00001', '00010', '00100', '01000', '01000', '01000'],
  8: ['01110', '10001', '10001', '01110', '10001', '10001', '01110'],
  9: ['01110', '10001', '10001', '01111', '00001', '00010', '01100'],
};

const GW = 5;
const GH = 7;

/** 글자 하나가 차지하는 폭 (자간 1칸 포함) */
const advance = (scale) => (GW + 1) * scale;

export const textWidth = (text, scale) => text.length * advance(scale) - scale;

/** (x, y) 왼쪽 위 기준으로 찍는다. 모르는 글자는 빈 칸으로 흘린다. */
export function drawBigText(ctx, text, x, y, scale, color) {
  ctx.fillStyle = color;
  let cx = Math.round(x);
  for (const ch of String(text).toUpperCase()) {
    const rows = GLYPHS[ch];
    if (rows) {
      for (let ry = 0; ry < GH; ry++) {
        for (let rx = 0; rx < GW; rx++) {
          if (rows[ry][rx] === '1') ctx.fillRect(cx + rx * scale, Math.round(y) + ry * scale, scale, scale);
        }
      }
    }
    cx += advance(scale);
  }
}

/** 가운데 정렬 + 그림자 한 겹 */
export function drawBigTextCentered(ctx, text, cx, y, scale, color, shadow = '#3a0b22') {
  const x = cx - textWidth(text, scale) / 2;
  if (shadow) drawBigText(ctx, text, x, y + scale, scale, shadow);
  drawBigText(ctx, text, x, y, scale, color);
}

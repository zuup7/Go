// 스테이지 타일맵.
//
// 한 스테이지는 "구간(chunk)" 을 옆으로 이어 붙여 만든다. 구간은 20칸 × 14줄이라
// 눈으로 보고 고칠 수 있다. 아래 compose() 가 구간을 한 줄짜리 맵으로 합친다.
//
// 글자 뜻
//   ' ' 빈 칸      '#' 땅          '=' 관통 발판     '?' 아이템 블록
//   'X' 낚시 블록  'I' 투명 블록   '%' 가짜 발판     '~' 역주행 바닥
//   '^' 가시       'v' 불쑥 가시   '*' 재생수(음표)  'S' 시작
//   ',' 무너지는 바닥  '|' 솟아오르는 벽  'R' 역재생 구간  '@' 정전 구간
//   'C' 체크포인트 'G' 골          'F' 도망가는 가짜 골
//   'a'~'q' 앨범 17종 스폰 (a=a01 … q=a17)

export const CHUNK_W = 20;
export const ROWS = 14;

/** 구간 하나. 14줄이 아니거나 20칸을 넘으면 즉시 알려준다. */
function chunk(name, rows) {
  if (rows.length !== ROWS) throw new Error(`구간 ${name}: ${ROWS}줄이어야 하는데 ${rows.length}줄`);
  return rows.map((row, i) => {
    if (row.length > CHUNK_W) throw new Error(`구간 ${name} ${i}줄: ${CHUNK_W}칸을 넘음 (${row.length})`);
    return row.padEnd(CHUNK_W, ' ');
  });
}

/** 구간들을 옆으로 이어 붙여 스테이지 줄 배열로 */
function compose(...chunks) {
  const rows = [];
  for (let r = 0; r < ROWS; r++) rows.push(chunks.map((c) => c[r]).join(''));
  return rows;
}

